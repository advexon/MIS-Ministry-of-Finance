export function documentText(key: string, locale: Locale = 'en'): string {
  const entry = Object.hasOwn(DOCUMENT_TRANSLATIONS, key) ? DOCUMENT_TRANSLATIONS[key] : undefined
  return entry?.[locale === 'ru' ? 1 : locale === 'tj' ? 2 : 0] ?? key
}

export function localizeDocumentTemplate(template: DocumentTemplate, locale: Locale): DocumentTemplate {
  const translateDefault = (value: string) => {
    const entry = Object.values(DOCUMENT_TRANSLATIONS).find(labels => labels.includes(value))
    return entry?.[locale === 'ru' ? 1 : locale === 'tj' ? 2 : 0] ?? value
  }
  return {
    ...template, locale,
    name: translateDefault(template.name),
    description: translateDefault(template.description),
    columns: template.columns.map(column => ({ ...column, label: translateDefault(column.label) })),
    headerFooter: {
      ...template.headerFooter,
      headerLeft: translateDefault(template.headerFooter.headerLeft),
      headerCenter: translateDefault(template.headerFooter.headerCenter),
      headerRight: translateDefault(template.headerFooter.headerRight),
      footerLeft: translateDefault(template.headerFooter.footerLeft),
      footerCenter: translateDefault(template.headerFooter.footerCenter),
      footerRight: translateDefault(template.headerFooter.footerRight),
    },
  }
}
